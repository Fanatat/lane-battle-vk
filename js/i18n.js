// Языки, для которых пока нет полного словаря в STRINGS, реально доступны
// как активный язык через resolveLang()/setLang() ниже — до заполнения
// остальных 9 словарей (следующий шаг этой же сессии, см. ТЗ) любой такой
// код фолбэчится на английский по общей цепочке.
const I18N = (() => {
  let lang = 'ru';

  function normalize(code) {
    if (!code) return null;
    const base = String(code).toLowerCase().split(/[-_]/)[0];
    return STRINGS[base] ? base : null;
  }

  function isSupported(code) {
    return !!normalize(code);
  }

  function interpolate(str, params) {
    if (!params) return str;
    let out = str;
    for (const key in params) {
      out = out.split('{' + key + '}').join(params[key]);
    }
    return out;
  }

  // Цепочка фолбэка (ТЗ, п.1): запрошенный язык → если его нет среди 11
  // словарей → английский → если и английского почему-то нет (не должно
  // случиться) → русский. Действует и на уровне выбора языка (setLang),
  // и повторно на уровне отдельного ключа (t) — двойная защита от падения,
  // если словарь конкретного языка когда-нибудь окажется неполным.
  function t(key, params) {
    const dict = STRINGS[lang];
    let str = dict && dict[key];
    if (str === undefined) str = STRINGS.en && STRINGS.en[key];
    if (str === undefined) str = STRINGS.ru && STRINGS.ru[key];
    if (str === undefined) return key;
    return interpolate(str, params);
  }

  function setLang(code) {
    lang = normalize(code) || (STRINGS.en ? 'en' : 'ru');
    document.documentElement.lang = lang;
    // dir НЕ ставится здесь намеренно (см. applyDirection() ниже) — CSS
    // `direction` наследуется по всему дереву документа, и dir="rtl" на
    // <html> зеркалит АБСОЛЮТНО всё, включая #hud/#toolbar (найдено живым
    // Playwright-прогоном: игровое поле реально поменялось местами, хотя
    // ТЗ п.4 требует зеркалить только текстовые контейнеры). <html> всегда
    // остаётся ltr — направление ставится точечно на .screen-элементы.
    document.documentElement.dir = 'ltr';
    return lang;
  }

  function getLang() { return lang; }

  // RTL (арабский) — ТОЛЬКО текстовые контейнеры интерфейса (меню/магазин/
  // попапы/справка), НЕ игровое поле и не HUD/тулбар — см. ТЗ, п.4 и
  // КОНЦЕПТ_ГДД.md, «Допущения». dir="rtl" ставится ТОЧЕЧНО на каждый
  // .screen-элемент (не на общего предка вроде <html>/<body>) — иначе CSS
  // `direction` наследуется вниз по всему дереву и зеркалит #hud/#toolbar
  // тоже, хотя они не являются потомками .screen (см. setLang() выше).
  function applyDirection() {
    const rtl = lang === 'ar';
    document.querySelectorAll('.screen').forEach((el) => {
      el.dir = rtl ? 'rtl' : 'ltr';
    });
  }

  // Переводит статическую разметку index.html: data-i18n → textContent,
  // data-i18n-html → innerHTML (для строк с <b>/<br>), data-i18n-title →
  // атрибут title (тултипы кнопок). Вызывается один раз при старте, ДО
  // первого showScreen() — см. game.js.
  function applyToDOM() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
      el.innerHTML = t(el.getAttribute('data-i18n-html'));
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });
    applyDirection();
  }

  return { t, setLang, getLang, isSupported, applyToDOM };
})();
